// Build the MCP Apps view (mcp-apps/prior-auth-summary) and wrap the single
// inlined HTML file as a TS string module the server can import without any
// file tracing. Run by `yarn build:mcp-app` and `prebuild`; the output is
// checked in so tests and `next dev` work without a build step.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const appDir = path.join(root, "mcp-apps/prior-auth-summary");

execFileSync(
  "npx",
  ["vite", "build", "--config", path.join(appDir, "vite.config.ts")],
  {
    cwd: root,
    stdio: "inherit",
  },
);

const html = readFileSync(path.join(appDir, "dist/index.html"), "utf8");
if (/<script[^>]+src=|<link[^>]+href=/i.test(html)) {
  throw new Error(
    "MCP App HTML references an external asset; it must be fully inlined.",
  );
}

const out = path.join(root, "lib/mcp/apps/generated/priorAuthSummaryHtml.ts");
writeFileSync(
  out,
  "// Generated by scripts/buildMcpApp.mjs from mcp-apps/prior-auth-summary. Do not edit.\n" +
    `export const PRIOR_AUTH_SUMMARY_HTML = ${JSON.stringify(html)};\n`,
);
console.log(
  `Wrote ${path.relative(root, out)} (${(html.length / 1024).toFixed(1)} KB)`,
);
